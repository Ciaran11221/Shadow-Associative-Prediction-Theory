#!/usr/bin/env python3
"""Rebuild INDEX.md from the corpus and check the theory's coverage.

Fails if:
  - a law in THEORY.md has no case or no test
  - a working rule in THEORY.md has no case
  - a case or shadow has no Sources section with at least one link
  - an id is duplicated, doesn't match its file name, or points at a law or rule that doesn't exist

Usage:
  python scripts/check_corpus.py           rewrite INDEX.md
  python scripts/check_corpus.py --check   fail if INDEX.md is out of date (used in CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAW = re.compile(r"^### (L\d+)\. (.+)$", re.M)
RULE = re.compile(r"^- \*\*(R\d+)\. (.+?)\*\*", re.M)
LINK = re.compile(r"\]\(https?://")
REQUIRED = {
    "cases": ["id", "title", "year", "laws", "rules"],
    "shadows": ["id", "title", "real", "proven", "useful"],
    "tests": ["id", "title", "law", "status"],
}
ALLOWED = {
    "real": {"yes", "partly", "no"},
    "proven": {"yes", "partly", "failed", "not-yet"},
    "useful": {"alerts", "history", "both", "no"},
    "status": {"planned", "running", "passed", "failed"},
}


def read(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def parse(path, errors):
    text = read(path)
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        errors.append(f"{path.name}: missing front matter")
        return None
    item = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [part.strip() for part in value[1:-1].split(",") if part.strip()]
        item[key.strip()] = value
    item["_body"] = text[match.end():]
    item["_file"] = path.name
    return item


def load(folder, errors):
    items = []
    for path in sorted((ROOT / folder).glob("*.md")):
        item = parse(path, errors)
        if item is None:
            continue
        missing = [key for key in REQUIRED[folder] if key not in item]
        if missing:
            errors.append(f"{path.name}: missing {', '.join(missing)}")
            continue
        for key in ("laws", "rules"):
            if isinstance(item.get(key), str):
                item[key] = [item[key]] if item[key] else []
        if not path.name.startswith(item["id"] + "-"):
            errors.append(f"{path.name}: file name must start with its id, {item['id']}")
        for key, allowed in ALLOWED.items():
            if key in item and item[key] not in allowed:
                errors.append(f"{path.name}: {key} '{item[key]}' must be one of {sorted(allowed)}")
        if folder in ("cases", "shadows"):
            after = item["_body"].split("## Sources", 1)
            if len(after) < 2 or not LINK.search(after[1]):
                errors.append(f"{path.name}: needs a '## Sources' section with at least one link")
        items.append(item)
    seen = set()
    for item in items:
        if item["id"] in seen:
            errors.append(f"{folder}: duplicate id {item['id']}")
        seen.add(item["id"])
    return items


def build_index(laws, rules, cases, shadows, tests):
    def link(item, folder):
        return f"[{item['id']}]({folder}/{item['_file']})"

    def links(items, folder):
        return ", ".join(link(item, folder) for item in items) or "none"

    lines = [
        "# Index",
        "",
        "Generated by `scripts/check_corpus.py`. Don't edit by hand: change the corpus and rerun the script.",
        "",
        f"{len(laws)} laws, {len(rules)} working rules, {len(cases)} cases, "
        f"{len(shadows)} shadows, {len(tests)} tests.",
        "",
        "## Laws",
        "",
        "| Law | Cases | Tests |",
        "|---|---|---|",
    ]
    for law, name in laws.items():
        law_cases = [case for case in cases if law in case["laws"]]
        law_tests = [test for test in tests if test["law"] == law]
        lines.append(f"| {law}. {name} | {links(law_cases, 'cases')} | {links(law_tests, 'tests')} |")
    lines += ["", "## Working rules", "", "| Rule | Cases |", "|---|---|"]
    for rule, name in rules.items():
        rule_cases = [case for case in cases if rule in case["rules"]]
        lines.append(f"| {rule}. {name} | {links(rule_cases, 'cases')} |")
    lines += ["", "## Cases", "", "| Case | Year | Title | Laws | Rules |", "|---|---|---|---|---|"]
    for case in cases:
        lines.append(
            f"| {link(case, 'cases')} | {case['year']} | {case['title']} "
            f"| {', '.join(case['laws']) or '-'} | {', '.join(case['rules']) or '-'} |"
        )
    lines += ["", "## Shadows", "", "| Shadow | Title | Real | Proven | Useful |", "|---|---|---|---|---|"]
    for shadow in shadows:
        lines.append(
            f"| {link(shadow, 'shadows')} | {shadow['title']} "
            f"| {shadow['real']} | {shadow['proven']} | {shadow['useful']} |"
        )
    lines += ["", "## Tests", "", "| Test | Law | Title | Status |", "|---|---|---|---|"]
    for test in tests:
        lines.append(f"| {link(test, 'tests')} | {test['law']} | {test['title']} | {test['status']} |")
    return "\n".join(lines) + "\n"


def main():
    check_only = "--check" in sys.argv[1:]
    errors = []
    theory = read(ROOT / "THEORY.md")
    laws = dict(LAW.findall(theory))
    rules = dict(RULE.findall(theory))
    if not laws:
        errors.append("THEORY.md: no laws found (expected '### L1. ...' headings)")
    if not rules:
        errors.append("THEORY.md: no working rules found (expected '- **R1. ...**' lines)")
    cases = load("cases", errors)
    shadows = load("shadows", errors)
    tests = load("tests", errors)

    for case in cases:
        for law in case["laws"]:
            if law not in laws:
                errors.append(f"{case['_file']}: unknown law {law}")
        for rule in case["rules"]:
            if rule not in rules:
                errors.append(f"{case['_file']}: unknown rule {rule}")
    for test in tests:
        if test["law"] not in laws:
            errors.append(f"{test['_file']}: unknown law {test['law']}")
    for law in laws:
        if not any(law in case["laws"] for case in cases):
            errors.append(f"{law} has no case")
        if not any(test["law"] == law for test in tests):
            errors.append(f"{law} has no test")
    for rule in rules:
        if not any(rule in case["rules"] for case in cases):
            errors.append(f"{rule} has no case")

    if errors:
        print("Corpus check failed:")
        for error in errors:
            print(f"  - {error}")
        return 1

    index = build_index(laws, rules, cases, shadows, tests)
    index_path = ROOT / "INDEX.md"
    if check_only:
        current = read(index_path) if index_path.exists() else ""
        if current != index:
            print("INDEX.md is out of date: run python scripts/check_corpus.py")
            return 1
    else:
        index_path.write_text(index, encoding="utf-8", newline="\n")
    print(
        f"OK: {len(laws)} laws, {len(rules)} working rules, {len(cases)} cases, "
        f"{len(shadows)} shadows, {len(tests)} tests. "
        "Every law has a case and a test; every rule has a case."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
